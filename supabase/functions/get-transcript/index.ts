function extractVideoId(url: string): string | null {
  const patterns = [
    /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/|youtube\.com\/v\/|youtube\.com\/shorts\/)([a-zA-Z0-9_-]{11})/,
    /^([a-zA-Z0-9_-]{11})$/,
  ];
  for (const p of patterns) {
    const m = url.match(p);
    if (m) return m[1];
  }
  return null;
}

interface TranscriptEntry { text: string; start: number; duration: number; }

function fmtTs(s: number): string {
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = Math.floor(s % 60), ms = Math.floor((s % 1) * 1000);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')},${String(ms).padStart(3, '0')}`;
}

function decodeHtmlEntities(text: string): string {
  return text
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&apos;/g, "'")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(parseInt(dec, 10)));
}

function dedup(entries: TranscriptEntry[]): TranscriptEntry[] {
  return entries.filter((e, i) => i === 0 || e.text !== entries[i - 1].text);
}

function parseJson3(json: any): TranscriptEntry[] {
  const entries: TranscriptEntry[] = [];
  for (const event of json?.events || []) {
    if (!event.segs) continue;
    const text = event.segs.map((s: any) => s.utf8 || '').join('').replace(/\n/g, ' ').trim();
    if (text) entries.push({ text, start: (event.tStartMs || 0) / 1000, duration: (event.dDurationMs || 0) / 1000 });
  }
  return entries;
}

function parseXml(xml: string): TranscriptEntry[] {
  const entries: TranscriptEntry[] = [];
  const regex = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  let m;
  while ((m = regex.exec(xml)) !== null) {
    const text = decodeHtmlEntities((m[3] || '').replace(/<[^>]+>/g, '')).replace(/\n/g, ' ').trim();
    if (text) entries.push({ text, start: parseFloat(m[1] || '0'), duration: parseFloat(m[2] || '0') });
  }
  return entries;
}

