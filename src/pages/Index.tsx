import { useState } from "react";
import { supabase } from "@/integrations/supabase/client";
import TranscriptForm from "@/components/TranscriptForm";
import TranscriptOutput from "@/components/TranscriptOutput";
import FAQSection from "@/components/FAQSection";
import ComingSoonSection from "@/components/ComingSoonSection";
import { AlertCircle, Youtube } from "lucide-react";

interface TranscriptData {
  videoId: string;
  videoTitle: string;
  plainText: string;
  timestampedText: string;
  srtContent: string;
  language: { code: string; name: string; isAutoGenerated: boolean };
  availableLanguages: Array<{ code: string; name: string; isAutoGenerated: boolean }>;
}

const Index = () => {
  const [transcript, setTranscript] = useState<TranscriptData | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [currentUrl, setCurrentUrl] = useState("");

  const fetchTranscript = async (url: string, language?: string) => {
    setIsLoading(true);
    setError(null);
    setCurrentUrl(url);

    try {
      const { data, error: fnError } = await supabase.functions.invoke("get-transcript", {
        body: { url, language },
      });

      if (fnError) {
        throw new Error(fnError.message || "Failed to fetch transcript");
      }

      if (data?.error) {
        throw new Error(data.error);
      }

      setTranscript(data);
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : "An unexpected error occurred";
      setError(message);
      setTranscript(null);
    } finally {
      setIsLoading(false);
    }
  };

  const handleLanguageChange = (code: string) => {
    if (currentUrl) {
      fetchTranscript(currentUrl, code);
    }
  };

  return (
    <div className="min-h-screen bg-background">
        {/* Hero */}
        <section className="gradient-hero py-20 sm:py-28 px-4">
          <div className="max-w-4xl mx-auto text-center">
            <div className="inline-flex items-center gap-2 bg-accent text-accent-foreground text-sm font-medium px-4 py-1.5 rounded-full mb-6 animate-fade-in">
              <Youtube className="h-4 w-4" />
              Free &amp; No API Key Required
            </div>
            <h1 className="font-heading text-4xl sm:text-5xl lg:text-6xl font-bold text-foreground leading-tight mb-4 animate-fade-in">
              YouTube Transcript Generator
            </h1>
            <p className="text-lg sm:text-xl text-muted-foreground max-w-2xl mx-auto mb-10 animate-fade-in">
              Convert any YouTube video into clean, readable text. Extract captions instantly — download as TXT or SRT.
            </p>
            <div className="animate-slide-up">
              <TranscriptForm onSubmit={(url) => fetchTranscript(url)} isLoading={isLoading} />
            </div>
          </div>
        </section>

        {/* Content */}
        <main className="px-4 py-12 space-y-16">
          {/* Error */}
          {error && (
            <div className="w-full max-w-2xl mx-auto animate-fade-in">
              <div className="flex items-start gap-3 bg-destructive/10 border border-destructive/20 rounded-xl p-4">
                <AlertCircle className="h-5 w-5 text-destructive mt-0.5 shrink-0" />
                <p className="text-sm text-destructive">{error}</p>
              </div>
            </div>
          )}

          {/* Transcript */}
          {transcript && (
            <TranscriptOutput
              plainText={transcript.plainText}
              timestampedText={transcript.timestampedText}
              srtContent={transcript.srtContent}
              videoTitle={transcript.videoTitle}
              language={transcript.language}
              availableLanguages={transcript.availableLanguages}
              onLanguageChange={handleLanguageChange}
            />
          )}

          {/* Features info */}
          {!transcript && !error && !isLoading && (
            <section className="w-full max-w-3xl mx-auto">
              <div className="grid sm:grid-cols-3 gap-6 text-center">
                {[
                  { title: "Paste URL", desc: "Enter any public YouTube video link" },
                  { title: "Extract", desc: "We fetch captions directly from YouTube" },
                  { title: "Download", desc: "Copy or download as TXT or SRT file" },
                ].map((step, i) => (
                  <div key={i} className="space-y-2">
                    <div className="inline-flex items-center justify-center w-10 h-10 rounded-full bg-primary text-primary-foreground font-heading font-bold text-sm">
                      {i + 1}
                    </div>
                    <h3 className="font-heading font-semibold text-foreground">{step.title}</h3>
                    <p className="text-sm text-muted-foreground">{step.desc}</p>
                  </div>
                ))}
              </div>
            </section>
          )}

          <ComingSoonSection />
          <FAQSection />
        </main>

        {/* Footer */}
        <footer className="border-t border-border py-8 px-4 text-center">
          <p className="text-sm text-muted-foreground">
            YouTube Transcript Generator — Free tool to convert YouTube videos to text.
          </p>
        </footer>
      </div>
  );
};

export default Index;
