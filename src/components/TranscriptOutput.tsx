import { useState } from "react";
import { Copy, Download, Check, Clock, AlignLeft } from "lucide-react";
import { Button } from "@/components/ui/button";
import { toast } from "sonner";

interface TranscriptOutputProps {
  plainText: string;
  timestampedText: string;
  srtContent: string;
  videoTitle: string;
  language: {
    code: string;
    name: string;
    isAutoGenerated: boolean;
  };
  availableLanguages: Array<{
    code: string;
    name: string;
    isAutoGenerated: boolean;
  }>;
  onLanguageChange: (code: string) => void;
}

const TranscriptOutput = ({
  plainText,
  timestampedText,
  srtContent,
  videoTitle,
  language,
  availableLanguages,
  onLanguageChange,
}: TranscriptOutputProps) => {
  const [showTimestamps, setShowTimestamps] = useState(false);
  const [copied, setCopied] = useState(false);

  const displayText = showTimestamps ? timestampedText : plainText;

  const handleCopy = async () => {
    await navigator.clipboard.writeText(displayText);
    setCopied(true);
    toast.success("Transcript copied to clipboard!");
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = (format: "txt" | "srt") => {
    const content = format === "srt" ? srtContent : displayText;
    const mimeType = "text/plain";
    const ext = format;
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${videoTitle.replace(/[^a-zA-Z0-9]/g, "_")}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success(`Downloaded as .${ext}`);
  };

  return (
    <div className="w-full max-w-3xl mx-auto animate-slide-up">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4">
        <div>
          <h2 className="font-heading text-lg font-semibold text-foreground">{videoTitle}</h2>
          <p className="text-sm text-muted-foreground">
            Language: {language.name}
            {language.isAutoGenerated && " (Auto-generated)"}
          </p>
        </div>
        {availableLanguages.length > 1 && (
          <select
            value={language.code}
            onChange={(e) => onLanguageChange(e.target.value)}
            className="px-3 py-2 rounded-lg border border-border bg-card text-sm text-foreground"
          >
            {availableLanguages.map((lang) => (
              <option key={lang.code} value={lang.code}>
                {lang.name} {lang.isAutoGenerated ? "(Auto)" : ""}
              </option>
            ))}
          </select>
        )}
      </div>

      {/* Controls */}
      <div className="flex flex-wrap items-center gap-2 mb-4">
        <Button
          variant={showTimestamps ? "default" : "outline"}
          size="sm"
          onClick={() => setShowTimestamps(!showTimestamps)}
          className="rounded-lg"
        >
          {showTimestamps ? <Clock className="mr-1.5 h-4 w-4" /> : <AlignLeft className="mr-1.5 h-4 w-4" />}
          {showTimestamps ? "Timestamps On" : "Timestamps Off"}
        </Button>
        <Button variant="outline" size="sm" onClick={handleCopy} className="rounded-lg">
          {copied ? <Check className="mr-1.5 h-4 w-4" /> : <Copy className="mr-1.5 h-4 w-4" />}
          {copied ? "Copied!" : "Copy"}
        </Button>
        <Button variant="outline" size="sm" onClick={() => handleDownload("txt")} className="rounded-lg">
          <Download className="mr-1.5 h-4 w-4" />
          .txt
        </Button>
        <Button variant="outline" size="sm" onClick={() => handleDownload("srt")} className="rounded-lg">
          <Download className="mr-1.5 h-4 w-4" />
          .srt
        </Button>
      </div>

      {/* Transcript */}
      <div className="bg-card border border-border rounded-xl p-6 max-h-[500px] overflow-y-auto">
        <pre className="whitespace-pre-wrap font-body text-sm leading-relaxed text-foreground">
          {displayText}
        </pre>
      </div>
    </div>
  );
};

export default TranscriptOutput;
